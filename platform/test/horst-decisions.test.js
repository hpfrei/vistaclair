// The decision ledger's carve-out for SERVER-DERIVED payload fields.
//
// The claim under test is a feedback loop, not a formatting preference.
// stats().editedFieldCounts feeds promptBlock(), which is spliced straight into
// draftReply's systemPrompt. So anything counted as an "edited field" becomes
// advice the drafting model receives next time.
//
// A composed reply carries its own sources (replyText, the quote, the snapshot
// signature) and lets the server recompute body/htmlBody from them. Flipping
// the signature checkbox therefore rewrites `body` without a human having
// touched a word — and without this carve-out that would teach the model "the
// body is usually rewritten before approval", a fabricated signal generated by
// a checkbox and fed back into the thing that writes the body.
//
// The carve-out is deliberately SCOPED: hand-composed mail has no sources to
// recompute from, so for those payloads `body` is the edit signal and must keep
// counting. Widening it to every payload would silence the real signal.
const test = require('node:test');
const assert = require('node:assert/strict');

const decisions = require('../src/apps/governance/horst-decisions');

const composedBefore = {
  account: 'hp@gmx.ch',
  to: 'anna@example.org',
  subject: 'Re: Rechnung 4711',
  replyText: 'Danke, ist überwiesen.',
  quotedText: 'Guten Tag,\n\nanbei die Rechnung 4711.',
  includeSignature: true,
  signatureText: 'Hans Peter\nVistaClair',
  composeVersion: 1,
  body: 'Danke, ist überwiesen.\n\n-- \nHans Peter\nVistaClair\n\n> Guten Tag,',
  htmlBody: '<div><p>Danke, ist überwiesen.</p></div>',
};

test('flipping the signature is not recorded as editing the draft', () => {
  const after = {
    ...composedBefore,
    includeSignature: false,
    // What the server's compose hook rewrites in response — no human touched it.
    body: 'Danke, ist überwiesen.\n\n> Guten Tag,',
    htmlBody: '<div><p>Danke, ist überwiesen.</p><blockquote>…</blockquote></div>',
  };
  const diff = decisions.diffPayloads(composedBefore, after);

  assert.deepEqual(diff.editedFields, ['includeSignature'],
    'only the flag the owner actually flipped may count as an edit');
  assert.ok(!diff.editedFields.includes('body'), 'a recomputed body is not a human edit');
  assert.ok(!diff.editedFields.includes('htmlBody'), 'a recomputed HTML part is not a human edit');
});

test('rewording a composed reply IS an edit, and the recomputation it causes is not', () => {
  const after = {
    ...composedBefore,
    replyText: 'Danke, die Zahlung ist raus.',
    body: 'Danke, die Zahlung ist raus.\n\n-- \nHans Peter\nVistaClair\n\n> Guten Tag,',
    htmlBody: '<div><p>Danke, die Zahlung ist raus.</p></div>',
  };
  const diff = decisions.diffPayloads(composedBefore, after);

  // The signal survives: the owner rewrote the words, and that is what the
  // ledger records — once, against the field they actually typed into.
  assert.deepEqual(diff.editedFields, ['replyText']);
  const entry = diff.editDiff.find((d) => d.field === 'replyText');
  assert.match(entry.after, /Zahlung ist raus/);
});

test('the carve-out does not apply to hand-composed mail, where body IS the signal', () => {
  // No replyText: nothing to recompute from, so an edited body is exactly what
  // it appears to be. Silencing it here would destroy the real preference data.
  const before = { account: 'hp@gmx.ch', to: 'anna@example.org', subject: 'Rechnung', body: 'Erste Fassung.' };
  const after = { ...before, body: 'Zweite Fassung.' };
  const diff = decisions.diffPayloads(before, after);

  assert.deepEqual(diff.editedFields, ['body'], 'a hand-edited body must still count');
});

test('an untouched payload produces no diff at all', () => {
  const diff = decisions.diffPayloads(composedBefore, { ...composedBefore });
  assert.equal(diff.editedFields, null);
  assert.equal(diff.editDiff, null);
});

test('the compact ledger row keeps the preference and previews the human words', () => {
  const row = decisions.compactPayload('email.send', composedBefore);

  assert.equal(row.includeSignature, true, 'the signature choice is preserved outside the edit signal');
  assert.equal(row.replyChars, composedBefore.replyText.length);
  // The preview answers "what did approved mail look like". For a composed
  // reply that is the authored part, not the trail it was stitched onto.
  assert.equal(row.bodyPreview, 'Danke, ist überwiesen.');
  assert.ok(!row.bodyPreview.includes('Guten Tag'), 'the preview must not be the quoted trail');
});

test('a legacy email row is unchanged by the new fields', () => {
  const row = decisions.compactPayload('email.send', {
    account: 'hp@gmx.ch', to: 'anna@example.org', subject: 'Rechnung', body: 'Erste Fassung.',
  });
  assert.equal(row.bodyPreview, 'Erste Fassung.');
  assert.equal(row.replyChars, null);
  assert.equal(row.includeSignature, null, 'absent is null, never a guessed default');
});
